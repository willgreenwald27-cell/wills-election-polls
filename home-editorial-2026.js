(()=>{
  'use strict';
  // Presentation-only enhancement. Do not overwrite stateData, polls,
  // forecast numbers, links, text, or interactive navigation handlers.
  const ROOT_SELECTOR='#page-home';
  let queued=false;
  let applying=false;
  const media=window.matchMedia('(max-width:1050px)');
  function setImportant(el,prop,value){
    if(!el)return;
    if(el.style.getPropertyValue(prop)===value&&el.style.getPropertyPriority(prop)==='important')return;
    el.style.setProperty(prop,value,'important');
  }
  function apply(){
    queued=false;
    if(applying)return;
    const root=document.querySelector(ROOT_SELECTOR);
    if(!root)return;
    const shell=root.querySelector('.reference-home-shell');
    const hero=shell?.querySelector('.reference-hero');
    const copy=hero?.querySelector('.reference-hero-copy');
    const metrics=shell?.querySelector('.reference-metrics');
    if(!shell||!hero||!metrics)return;
    applying=true;
    try{
      // Existing model-methodology note gets a proper place inside the
      // original hero. We move its actual node and keep its exact text.
      const modelNote=root.querySelector('#homeModelNote');
      if(modelNote&&copy&&modelNote.parentElement!==copy)copy.appendChild(modelNote);
      shell.classList.add('will-editorial-home-v1');

      // Another installed script writes an !important 1-column grid into
      // inline styles. Give its existing four cards the new layout without
      // re-creating or changing any card contents.
      setImportant(metrics,'display','grid');
      setImportant(metrics,'grid-template-columns','repeat(2,minmax(0,1fr))');
      setImportant(metrics,'grid-auto-flow','row');
      setImportant(metrics,'gap',media.matches?'8px':'10px');
      setImportant(metrics,'width','100%');
      const positions=[
        ['#homeElectionCountdown','1 / -1','1'],
        ['#homeSenateTossups','1','2'],
        ['#homeLastUpdated','2','2'],
        ['#homeSenateForecast','1 / -1','3']
      ];
      for(const [selector,column,row] of positions){
        const el=metrics.querySelector(selector);
        if(!el)continue;
        setImportant(el,'grid-column',column);
        setImportant(el,'grid-row',row);
      }
    }finally{applying=false;}
  }
  function schedule(){
    if(queued)return;
    queued=true;
    requestAnimationFrame(apply);
  }
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',apply,{once:true});else apply();
  // Home counters are regenerated by legacy scripts on navigation and
  // resizing. Reapply only layout styles after those DOM changes.
  const root=document.querySelector(ROOT_SELECTOR);
  if(root)new MutationObserver(schedule).observe(root,{childList:true,subtree:true});
  [80,300,950,1900,3500].forEach(ms=>setTimeout(apply,ms));
  window.addEventListener('pageshow',apply);
  window.addEventListener('resize',schedule);
})();
